import type {
	CanonicalConversationItem,
	ExtensionApprovalScope,
	InstructionFragmentKind,
	ProviderUsage,
	RuntimeErrorCode,
	ToolDefinition,
} from "@mycli/core";
import type { ExtensionToolApprovalPolicy, ToolAdapter } from "@mycli/tools";

/**
 * Where a turn came from: a human submission, another agent, or the goal extension's continuation.
 * The set stays closed because storage persists the label and the transcript renders it — a second
 * extension that admits turns has no label of its own yet and has to borrow one, which is not
 * neutral (see the durable-source note in docs/architecture/extension-api.md).
 */
export type ExtensionTurnSource = "user" | "agent_mailbox" | "goal";

/** Identifies the extension that admitted a turn, plus the opaque handle it issued. */
export interface ExtensionAdmissionRef {
	readonly extensionId: string;
	/**
	 * Opaque to the runtime and to every other extension: only the admitting extension interprets
	 * it. It is never persisted, so it may hold a live reference the extension owns.
	 */
	readonly reference?: unknown;
}

export interface ExtensionAdmissionInput {
	readonly sessionId: string;
	/** Tool names currently exposed, so an admission can shape the message it hands the model. */
	readonly toolNames: readonly string[];
}

/** A turn an extension asks the runtime to start while the session is otherwise idle. */
export interface ExtensionAdmission {
	/** Durable label recorded for this turn. */
	readonly source: ExtensionTurnSource;
	/** The input the model receives. Generated by the extension, never typed by a human. */
	readonly message: string;
	readonly reference?: unknown;
}

export interface ExtensionAdmissionFailureInput {
	readonly sessionId: string;
	readonly reference?: unknown;
	readonly message: string;
}

export interface ExtensionAdmittedTurnInput {
	readonly sessionId: string;
	readonly turnId: string;
	readonly source: ExtensionTurnSource;
	/** Present only when this turn came from an extension admission. */
	readonly admission?: ExtensionAdmissionRef;
}

export interface ExtensionFinishedTurnInput extends ExtensionAdmittedTurnInput {
	readonly status: string;
	readonly errorCode?: string;
}

/**
 * The view a contributor gets of the turn it is observing. It deliberately carries only what every
 * lifecycle point has in common, so the core never has to know which extension needs what.
 */
export interface ExtensionTurnInput {
	readonly sessionId: string;
	readonly turnId: string;
	readonly workspaceRoot: string;
	readonly source: ExtensionTurnSource;
	readonly message: string;
	readonly signal: AbortSignal;
}

export interface ExtensionTurnCompleteInput extends ExtensionTurnInput {
	readonly assistantText: string;
	readonly usage: ProviderUsage;
	/** False when the terminal snapshot could not be written, so durable side effects are unsafe. */
	readonly terminalSnapshotWritten: boolean;
}

export interface ExtensionTokenUsageInput {
	readonly sessionId: string;
	readonly turnId: string;
	/** Identifies the provider request the usage belongs to, so accounting stays idempotent. */
	readonly requestId: string;
	readonly usage: ProviderUsage;
	/**
	 * `attempt` for usage a retry attempt reported while it was still streaming, `final` for the
	 * step's settled usage.
	 *
	 * A step reports its settled usage only when no attempt reported any, so every observation is
	 * distinct and a feature that keys on `requestId` never counts the same work twice. A retry
	 * attempt that cost tokens but then failed still reports them, and a response with no usage at
	 * all reports an empty usage so the cost is recorded as unknown instead of free.
	 */
	readonly phase: "attempt" | "final";
	/** The retry attempt index, present for the `attempt` phase. */
	readonly attempt?: number;
}

export interface TurnLifecycleContributor {
	/**
	 * Runs once the turn is admitted and before it is prepared, so bookkeeping that the context
	 * hooks depend on is in place. Failures are isolated: a feature that cannot register the turn
	 * must not stop the turn from running.
	 */
	onTurnAdmitted?(input: ExtensionAdmittedTurnInput): void | Promise<void>;
	/** Runs once the turn is admitted and before the first provider request. */
	onTurnStart?(input: ExtensionTurnInput): void | Promise<void>;
	/** Runs after a turn completes; failures are isolated. */
	onTurnComplete?(input: ExtensionTurnCompleteInput): void | Promise<void>;
	/** Runs after a turn reaches a terminal state, whatever that state is. */
	onTurnFinished?(input: ExtensionFinishedTurnInput): void | Promise<void>;
}

/**
 * Lets an extension start turns on its own. Only one admission is honoured per scheduler pass, so
 * the first extension in registration order that wants a turn gets it.
 */
export interface AdmissionContributor {
	/**
	 * Asks whether the extension wants a new turn started while the session is idle. Synchronous by
	 * contract: the turn scheduler is synchronous and cannot await a decision.
	 */
	nextTurn?(input: ExtensionAdmissionInput): ExtensionAdmission | undefined;
	/**
	 * Validates a previously issued admission before the runtime reserves the turn. Admission is
	 * contract-bearing, so a throw rejects the turn instead of being isolated like the other hooks.
	 */
	assertAdmission?(input: { readonly sessionId: string; readonly reference?: unknown }): void;
	/** The runtime could not start the admitted turn; the owner records why. */
	onAdmissionFailed?(input: ExtensionAdmissionFailureInput): void;
}

export interface ExtensionTurnPolicyInput {
	readonly sessionId: string;
	readonly turnId: string;
}

/** Why an extension stopped a turn. The runtime validates `interruptionReason` against the contract. */
export interface ExtensionTurnStop {
	readonly message: string;
	readonly interruptionReason?: string;
}

/**
 * Lets an extension end a running turn or take its tools away, which is how a feature enforces a
 * budget it owns. `stopReason` and `toolsStopReason` are pure reads; `allowTools` is stateful,
 * because the owner is the one that knows when its single wrap-up step has been served.
 */
export interface TurnPolicyContributor {
	/** Why the turn must stop before the next provider step. The first contributor wins. */
	stopReason?(input: ExtensionTurnPolicyInput): ExtensionTurnStop | undefined;
	/** Why tools must not run for the pending batch. The first contributor wins. */
	toolsStopReason?(input: ExtensionTurnPolicyInput): ExtensionTurnStop | undefined;
	/**
	 * Whether the next provider step may carry tools. Every contributor is asked and a single
	 * `false` strips them, which is how a budget-exhausted feature offers its one wrap-up step. The
	 * owner decides when that step has been served; it is asked again on every step.
	 */
	allowTools?(input: ExtensionTurnPolicyInput): boolean;
}

/**
 * Lets an extension own the session-level lifecycle of the state it drives, so the app does not
 * have to name the feature that pauses on a cold start or releases resources on close.
 */
export interface SessionLifecycleContributor {
	/** The session was activated. A feature must not resume work it cannot confirm after a restart. */
	onRestore?(): void;
	/** The user interrupted the running turn; pause anything the feature was driving. */
	onInterrupt?(): void;
	/** The session is closing; release resources. */
	onClose?(): void;
}

/**
 * Which subsystem owns a contributed tool. Mirrors the integration sources, because a contribution
 * is merged into the same catalog, and the source still decides discovery: `mcp` and `plugin` tools
 * are discovered on demand. Approval is not derived from the source — the feature sets it.
 */
export type ExtensionToolSource = "skill" | "mcp" | "plugin" | "subagent";

/**
 * A tool an extension contributes together with the catalog metadata the session needs: whether it
 * is model-visible or discovered on demand, how it is approved, and where it came from. A plain
 * `ToolAdapter` is enough when none of that applies.
 */
export interface ExtensionToolRegistration {
	readonly id: string;
	readonly source: ExtensionToolSource;
	readonly definition: ToolDefinition;
	readonly adapter: ToolAdapter;
	readonly originMetadata?: Readonly<Record<string, string>>;
	readonly sourceDescription?: string;
	readonly modelVisible?: boolean;
	readonly supportsParallelToolCalls?: boolean;
	readonly approvalPolicy?: ExtensionToolApprovalPolicy["approvalPolicy"];
	readonly approvalScope?: ExtensionApprovalScope;
	readonly annotations?: ExtensionToolApprovalPolicy["annotations"];
}

export interface ToolContributor {
	/**
	 * Adapters for this session's static catalog. Called whenever the catalog is rebuilt, so the
	 * extension may build them lazily and keep them out of the model's view until then.
	 */
	tools?(): readonly ToolAdapter[];
	/**
	 * Registrations that also carry catalog metadata. The session merges them into the integration
	 * catalog and hands the extension's sources over to it, so the app stops naming them.
	 */
	toolRegistrations?(): readonly ExtensionToolRegistration[];
}

/** Instructions for one skill the user selected on this turn. */
export interface ExtensionSkillInstructions {
	readonly skillId: string;
	readonly content: string;
}

export interface ExtensionSkillInput {
	readonly sessionId: string;
	readonly turnId: string;
}

/**
 * Lets an extension own the skills a session can invoke: the catalog the model reads, the tool
 * registrations that invoke them (contributed through `tools`), and the instructions for the
 * skills selected on a turn.
 */
export interface SkillContributor {
	/** Model-visible catalog of the skills this session can invoke, or empty when it has none. */
	skillCatalog?(): string | undefined;
	/** Instructions for the skills selected on this turn. */
	selectedInstructions?(input: ExtensionSkillInput): readonly ExtensionSkillInstructions[] | undefined;
}

export interface ExtensionCompactionBudgetInput {
	readonly sessionId: string;
	/** The turn being compacted, when compaction runs inside one. */
	readonly turnId?: string;
}

/**
 * The account a compaction summary is charged to. Resolved once per compaction so the owner can
 * capture which account it is charging, while the remaining amount is read fresh — a compaction
 * attempt can itself consume the budget it is being limited by.
 */
export interface ExtensionCompactionBudget {
	/** Remaining tokens for the summary; `undefined` means unbounded. */
	remainingTokenBudget(): number | undefined;
	/** Attribute one compaction attempt's usage. */
	observeUsage(requestId: string, usage: ProviderUsage): void;
}

/**
 * Lets an extension enforce its own budget on the compaction summarizer, so compaction does not
 * have to know which feature is accounting for the tokens it spends.
 */
export interface CompactionBudgetContributor {
	compactionBudget?(input: ExtensionCompactionBudgetInput): ExtensionCompactionBudget | undefined;
}

export interface ExtensionTurnContextInput {
	readonly sessionId: string;
	readonly turnId: string;
}

/**
 * Lets an extension fill the session's `conversation_context` fragment. That fragment keeps its own
 * kind and its own position in the instruction list, so the slot decides *who* fills it rather than
 * what it renders as — moving it into `context` sections would reorder the model input.
 */
export interface ConversationContextContributor {
	conversationContext?(input: ExtensionTurnContextInput): string | undefined;
}

/**
 * Lets an extension carry its accounting across a runtime boundary: the parent runtime captures a
 * handle for the turn that delegated work, and the child runtime adopts it for the turn doing that
 * work.
 *
 * Handles are opaque, and the extension that captures one is not necessarily the extension that
 * adopts it (goal captures on the parent side, goal-usage adopts on the child side). So every
 * captured handle is offered to every extension and an extension ignores the ones it does not
 * recognise.
 */
export interface DelegationContributor {
	/** The handle for what this runtime accounts for on `turnId`, or undefined when it accounts nothing. */
	captureDelegatedWork?(input: ExtensionTurnContextInput): unknown;
	/** Consider one captured handle; ignore it when it belongs to another extension. */
	bindDelegatedWork?(input: ExtensionTurnContextInput & { readonly handle: unknown }): void;
	/** The delegated turn ended; drop the binding. */
	releaseDelegatedWork?(input: ExtensionTurnContextInput): void;
}

/** The runtime failure an extension's own error should be reported as. */
export interface ExtensionFailureMapping {
	readonly code: RuntimeErrorCode;
	readonly message: string;
	readonly retryable?: boolean;
}

/**
 * Lets an extension classify an error it raised, so the turn reports the failure the feature means
 * instead of a generic internal error. The first mapping wins, and an extension returns undefined
 * for errors it does not own.
 */
export interface FailureContributor {
	normalizeFailure?(input: { readonly error: unknown }): ExtensionFailureMapping | undefined;
}

export interface ConversationItemContributor {
	/**
	 * Items the runtime inserts ahead of the current user input, mirroring how memory is injected.
	 * Return `undefined` to contribute nothing for this turn.
	 */
	conversationItems?(
		input: ExtensionTurnInput,
	): readonly CanonicalConversationItem[] | undefined | Promise<readonly CanonicalConversationItem[] | undefined>;
}

export interface TokenUsageContributor {
	onTokenUsage?(input: ExtensionTokenUsageInput): void | Promise<void>;
}

/**
 * A turn-context section an extension contributes. The extension owns the identity (`key`,
 * `kind`, `title`, `source`) and the rendered `content`, so migrating a feature onto the registry
 * does not change the bytes the model sees.
 */
export interface ExtensionContextSection {
	readonly key: string;
	readonly kind: InstructionFragmentKind;
	readonly title: string;
	readonly content: string;
	readonly source: string;
	/** Trusted policy-producing sections carry developer authority, like trusted hook context. */
	readonly trusted?: boolean;
	readonly policyProducing?: boolean;
	readonly cacheClass?: "static" | "dynamic" | "ephemeral";
	readonly scope?: "turn" | "transcript" | "session";
	readonly includeInMemory?: boolean;
	readonly required?: boolean;
}

export interface ContextContributor {
	context?(
		input: ExtensionTurnInput,
	): readonly ExtensionContextSection[] | undefined | Promise<readonly ExtensionContextSection[] | undefined>;
}

/** One registered feature. `id` is the stable identity used for ordering, tracing, and failures. */
export interface ExtensionDefinition {
	readonly id: string;
	readonly admission?: AdmissionContributor;
	readonly turnPolicy?: TurnPolicyContributor;
	readonly sessionLifecycle?: SessionLifecycleContributor;
	readonly tools?: ToolContributor;
	readonly skills?: SkillContributor;
	readonly compactionBudget?: CompactionBudgetContributor;
	readonly conversationContext?: ConversationContextContributor;
	readonly delegation?: DelegationContributor;
	readonly failure?: FailureContributor;
	readonly turnLifecycle?: TurnLifecycleContributor;
	readonly conversationItems?: ConversationItemContributor;
	readonly context?: ContextContributor;
	readonly tokenUsage?: TokenUsageContributor;
}
